# Device discovery
# ---------------------------------------------------------------------------
@dataclass
class Device:
    label: str  # text shown in the list
    path: str  # what gets handed to the CLI (--port / --sd-device)
    blocked: str = ""  # non-empty = never offer this one (and why)
    preferred: bool = False  # pre-select it when nothing else is selected


def fmt_size(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1000:
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1000
    return f"{n:.1f} TB"


def list_serial_ports() -> list[Device]:
    devices = []
    for info in QSerialPortInfo.availablePorts():
        desc = info.description() or info.manufacturer() or "serial port"
        ids = (
            f"  [{info.vendorIdentifier():04x}:{info.productIdentifier():04x}]"
            if info.hasVendorIdentifier() and info.hasProductIdentifier()
            else ""
        )
        devices.append(
            Device(
                f"{info.portName()} - {desc}{ids}",
                info.systemLocation(),  # gives \\.\COM5 on Windows, so COM10+ works in gdb too
                preferred="gdb" in desc.lower(),
            )
        )
    return sorted(devices, key=lambda d: (len(d.path), d.path))


_PS_DISKS = (
    "try{[Console]::OutputEncoding=[Text.Encoding]::UTF8}catch{};"
    "Get-Disk | Select-Object Number,FriendlyName,Size,"
    "@{n='Bus';e={[string]$_.BusType}},IsBoot,IsSystem | ConvertTo-Json -Compress"
)


def parse_windows_disks(text: str) -> list[Device]:
    text = text.strip()
    if not text:
        return []
    data = json.loads(text)
    if isinstance(
        data, dict
    ):  # PowerShell emits a bare object when there is only one disk
        data = [data]
    devices = []
    for d in data:
        size = int(d.get("Size") or 0)
        if size == 0:  # empty card-reader slot
            continue
        number = d["Number"]
        name = (d.get("FriendlyName") or "unknown").strip()
        blocked = "system/boot disk" if d.get("IsSystem") or d.get("IsBoot") else ""
        label = (
            f"PhysicalDrive{number} - {name} ({d.get('Bus') or '?'}, {fmt_size(size)})"
        )
        if blocked:
            label += f"  [blocked: {blocked}]"
        devices.append(Device(label, rf"\\.\PhysicalDrive{number}", blocked))
    return devices


def parse_lsblk(text: str) -> list[Device]:
    def mounts(node):
        found = [node["mountpoint"]] if node.get("mountpoint") else []
        for child in node.get("children") or []:
            found += mounts(child)
        return found

    devices = []
    for d in json.loads(text).get("blockdevices", []):
        if d.get("type") != "disk" or d["name"].startswith(
            ("loop", "ram", "zram", "nbd")
        ):
            continue
        size = int(d.get("size") or 0)
        if size == 0:
            continue
        mp = mounts(d)
        blocked = (
            "holds the running system"
            if any(m == "/" or m.startswith("/boot") or m == "[SWAP]" for m in mp)
            else ""
        )
        path = d.get("path") or "/dev/" + d["name"]
        bus = (d.get("tran") or "").upper()
        label = f"{path} - {(d.get('model') or 'unknown').strip()} ({bus + ', ' if bus else ''}{fmt_size(size)})"
        if blocked:
            label += f"  [blocked: {blocked}]"
        elif mp:
            label += f"  [mounted: {', '.join(mp)}]"
        devices.append(Device(label, path, blocked))
    return devices


def list_sd_devices() -> list[Device]:
    """Blocking (shells out to PowerShell / lsblk), so it is only ever called from a worker thread."""
    if WINDOWS:
        r = subprocess.run(
            ["powershell", "-NoProfile", "-NonInteractive", "-Command", _PS_DISKS],
            capture_output=True,
            text=True,
            encoding="utf-8-sig",
            errors="replace",  # -sig: PowerShell may prepend a BOM
            timeout=30,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        if r.returncode:
            raise RuntimeError((r.stderr or "Get-Disk failed").strip())
        return parse_windows_disks(r.stdout)
    if platform.system() == "Linux":
        r = subprocess.run(
            ["lsblk", "-J", "-b", "-o", "NAME,PATH,SIZE,MODEL,TRAN,TYPE,MOUNTPOINT"],
            capture_output=True,
            text=True,
            timeout=15,
        )
        if r.returncode:
            raise RuntimeError((r.stderr or "lsblk failed").strip())
        return parse_lsblk(r.stdout)
    return []  # macOS etc.: add the device by hand (Devices > Add SD device path...)


def is_admin() -> bool:
    try:
        return bool(ctypes.windll.shell32.IsUserAnAdmin())
    except Exception:
        return True  # can't tell - don't nag


# ---------------------------------------------------------------------------
# Background worker: runs a function with print() output sent to the log
# ---------------------------------------------------------------------------
class _SignalStream(io.TextIOBase):
    """File-like object that forwards everything written to it to a Qt signal."""

    def __init__(self, signal):
        self._signal = signal

    def writable(self):
        return True

    def write(self, text):
        if text:
            self._signal.emit(text)
        return len(text)


class Task(QtCore.QThread):
    log = QtCore.pyqtSignal(str)
    done = QtCore.pyqtSignal(bool, object)  # (ok, result or error message)

    def __init__(self, fn, workdir=None):
        super().__init__()
        self.fn, self.workdir = fn, workdir

    def run(self):
        out = _SignalStream(self.log)
        cwd = (
            contextlib.chdir(self.workdir) if self.workdir else contextlib.nullcontext()
        )
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out), cwd:
                result = self.fn()
        except (
            SystemExit
        ) as exc:  # the CLI reports every failure as sys.exit("message")
            ok = exc.code in (None, 0)
            self.done.emit(ok, None if ok else str(exc.code))
        except Exception as exc:
            self.done.emit(False, f"{type(exc).__name__}: {exc}")
        else:
            self.done.emit(True, result)


# ---------------------------------------------------------------------------
# Steps: thin wrappers around the CLI's own functions. They run inside the
# backup folder, so every file name below is relative - that keeps spaces and
# backslashes out of the gdb command lines (gdb's `dump`/`load` choke on both).
# ---------------------------------------------------------------------------
def _replace_atomically(final: str, produce):
    """produce(part_name) writes a new file; only if that succeeds does it replace `final`.
    A failed dump therefore can't clobber the existing backup, nor pass off the old file as new.
    """
    final = Path(final)
    part = final.with_name(final.name + ".part")
    part.unlink(missing_ok=True)
    try:
        produce(str(part))
        os.replace(part, final)
        print(f"[gui] saved {final.resolve()}")
    finally:
        part.unlink(missing_ok=True)


def step_dump_flash(ns):
    def produce(part):
        ns.flash_out = part
        cli.backup_flash(ns)

    _replace_atomically(cli.DEFAULT_FLASH_FILE, produce)


def step_dump_sd(ns):
    def produce(part):
        ns.sd_out = part
        cli.backup_sd(ns)

    _replace_atomically(cli.DEFAULT_SD_FILE, produce)


def step_write_flash(ns):
    # restore_flash() reads the flash back into <backup>.verify.bin and compares hashes. A copy left over from an
    # earlier run would "verify" even if the new read-back silently failed, so start from a clean slate.
    src = Path(ns.flash_in)
    src.with_name(src.stem + ".verify.bin").unlink(missing_ok=True)
    cli.restore_flash(ns)


def step_write_sd(ns):
    cli.restore_sd(ns)


